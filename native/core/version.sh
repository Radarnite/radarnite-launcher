#!/usr/bin/env bash
# version.sh <semver> - print the version.gen.h of a build for that version (read by version.h when RN_VERSION_GEN is
# defined). native/core/build.sh runs it for RN_VERSION; `just build-pc` runs it on the dev box and ships the header
# to build.cmd (cmd has no semver parser).
#   3.0.0-rc.1 -> RN_VERSION_STR "3.0.0-rc.1", FILEVERSION 3,0,0,1 ("3.0.0.1"), VS_FF_PRERELEASE
#   3.0.0      -> RN_VERSION_STR "3.0.0",      FILEVERSION 3,0,0,0 ("3.0.0.0")
# The 4th field is the last pre-release identifier when it is a number (0 otherwise): informational only, the
# updater compares the full string.
set -euo pipefail
v="${1:-}"
die() { echo "version.sh: $*" >&2; exit 1; }
re='^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-([0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*))?$'
[[ "$v" =~ $re ]] || die "'$v' is not a semver version (3.0.0, 3.0.0-rc.1; no build metadata)"
maj="${BASH_REMATCH[1]}"; min="${BASH_REMATCH[2]}"; pat="${BASH_REMATCH[3]}"; pre="${BASH_REMATCH[5]}"
for n in "$maj" "$min" "$pat"; do [ "${#n}" -le 5 ] && [ "$n" -le 65535 ] || die "'$v': $n does not fit a FILEVERSION field"; done
build=0; flags=0x0L
if [ -n "$pre" ]; then
  flags=0x2L
  last="${pre##*.}"
  if [[ "$last" =~ ^[0-9]{1,5}$ ]] && [ "$((10#$last))" -le 65535 ]; then build=$((10#$last)); fi
fi
cat <<EOF
// Generated by native/core/version.sh $v (do not edit, do not commit)
#define RN_VERSION_STR "$v"
#define RN_VERSION_MAJOR $maj
#define RN_VERSION_MINOR $min
#define RN_VERSION_PATCH $pat
#define RN_VERSION_BUILD $build
#define RN_VERSION_FILE_STR "$maj.$min.$pat.$build"
#define RN_VERSION_FLAGS $flags
EOF
