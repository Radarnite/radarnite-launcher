#!/usr/bin/env bash
# vendor-pak-tools.sh - the pak tools the launcher ships in <program>\tools, kept in paktools/ as the one copy:
# fn-modkit sigfit (fn-modkit-sigfit\ + sigfit-installed.ps1, run before each classic-pak launch) and game-guard.ps1
# (refuses automated launches next to an anti-cheat or another game), all from fn-viewer's tools/fn-modkit.
#
#   tools/vendor-pak-tools.sh update <fn-viewer checkout> [pc mirror]   build fn-modkit there on the PC, then import it
#   tools/vendor-pak-tools.sh import <built fn-modkit folder> <fn-viewer checkout>
#   tools/vendor-pak-tools.sh check     paktools/ matches its manifest and native/core/paktools_manifest.h matches both
#   tools/vendor-pak-tools.sh header    print the header for the current manifest
#
# update: the checkout must be clean (its short commit is the version); fn-modkit is built through the checkout's own
# PC lane (tools/win-build.sh, mirror default rl-paktools) as Release, deterministic, with no PDB, so the binaries carry
# no build path. import: replaces paktools/ whole, applies release.sh's same-length scrub (so release.sh's own scrub
# finds nothing to change and the shipped files are these, byte for byte), writes paktools/pak-tools.manifest
# ("<sha256>  <path>", sorted) and native/core/paktools_manifest.h, and runs the privacy gate on paktools/.
# release.sh refuses a payload that carries its own copy of these tools and checks the staged ones against the
# manifest; the launcher checks the installed ones against the header before running them.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
P="$ROOT/paktools"; M="$P/pak-tools.manifest"; H="$ROOT/native/core/paktools_manifest.h"
die() { echo "vendor-pak-tools: $*" >&2; exit 1; }
sha256() { if command -v shasum >/dev/null; then shasum -a 256 "$1" | cut -d' ' -f1; else sha256sum "$1" | cut -d' ' -f1; fi; }

listed() { grep -v '^#' "$M" | awk -v f="$1" '$2 == f { found = 1 } END { exit !found }'; }
manifest_version() { sed -n 's/^# version \([0-9a-f]\{7,40\}\)$/\1/p' "$M"; }

header() {
  [ -f "$M" ] || die "no $M"
  local v; v="$(manifest_version)"; [ -n "$v" ] || die "$M has no '# version <commit>' line"
  echo "// Generated by tools/vendor-pak-tools.sh from paktools/pak-tools.manifest: do not edit."
  echo "// The pak tools this launcher was built with (paktools.h): every file of <launcher>\\tools it checks, and its sha256."
  echo "#pragma once"
  echo "#define RN_PAKTOOLS_VERSION L\"$v\""
  echo "struct PakToolFile { const wchar_t* path; const char* sha256; };"
  echo "static const PakToolFile kPakTools[] = {"
  grep -v '^#' "$M" | while read -r h f; do printf '    { L"%s", "%s" },\n' "${f//\//\\\\}" "$h"; done
  echo "};"
}

check() {
  [ -f "$M" ] || die "no $M (tools/vendor-pak-tools.sh update)"
  local bad=0 n=0 h f
  while read -r h f; do
    n=$((n + 1))
    [ -f "$P/$f" ] || { echo "missing paktools/$f" >&2; bad=1; continue; }
    [ "$(sha256 "$P/$f")" = "$h" ] || { echo "paktools/$f differs from the manifest" >&2; bad=1; }
  done < <(grep -v '^#' "$M")
  while IFS= read -r f; do
    listed "$f" || { echo "paktools/$f is not in the manifest" >&2; bad=1; }
  done < <(cd "$P" && find . -type f ! -name pak-tools.manifest | sed 's|^\./||' | LC_ALL=C sort)
  for f in sigfit-installed.ps1 game-guard.ps1 fn-modkit-sigfit/fn-modkit.dll; do
    listed "$f" || { echo "the manifest lacks $f" >&2; bad=1; }
  done
  cmp -s "$H" <(header) || { echo "native/core/paktools_manifest.h does not match the manifest (tools/vendor-pak-tools.sh header)" >&2; bad=1; }
  [ "$bad" = 0 ] || die "paktools/ is not consistent"
  echo "pak tools $(manifest_version): $n files, manifest and header match"
}

import() {
  local built="${1:?usage: import <built fn-modkit folder> <fn-viewer checkout>}" fv="${2:?usage: import <built folder> <fn-viewer checkout>}"
  local w="$fv/tools/fn-modkit/windows"
  [ -f "$built/fn-modkit.dll" ] || die "$built has no fn-modkit.dll"
  [ -f "$w/sigfit-installed.ps1" ] && [ -f "$w/game-guard.ps1" ] || die "$w lacks sigfit-installed.ps1 or game-guard.ps1"
  local v; v="$(git -C "$fv" rev-parse --short=8 HEAD)"
  [ -z "$(git -C "$fv" status --porcelain -- tools/fn-modkit external/CUE4Parse)" ] || die "$fv has uncommitted changes in tools/fn-modkit: commit them first (the commit is the version)"
  rm -rf "${P:?}"; mkdir -p "$P/fn-modkit-sigfit"
  cp -R "$built/." "$P/fn-modkit-sigfit/"
  find "$P" -type f -iname '*.pdb' -delete
  cp "$w/sigfit-installed.ps1" "$w/game-guard.ps1" "$P/"
  "$ROOT/tools/release.sh" scrub "$P"
  {
    echo "# Radarnite Launcher pak tools: fn-modkit sigfit and the game guard from fn-viewer tools/fn-modkit (tools/vendor-pak-tools.sh)"
    echo "# version $v"
    (cd "$P" && find . -type f ! -name pak-tools.manifest | sed 's|^\./||' | LC_ALL=C sort | while IFS= read -r f; do echo "$(sha256 "$f")  $f"; done)
  } > "$M"
  header > "$H"
  "$ROOT/tools/release.sh" privacy-scan "$P" || die "paktools/ carries a builder path or identity: not vendored as is"
  check
}

update() {
  local fv="${1:?usage: update <fn-viewer checkout> [pc mirror]}" mirror="${2:-rl-paktools}"
  fv="$(cd "$fv" && pwd)"
  [ -x "$fv/tools/win-build.sh" ] || die "$fv/tools/win-build.sh not found (an fn-viewer checkout?)"
  [ -z "$(git -C "$fv" status --porcelain -- tools/fn-modkit external/CUE4Parse)" ] || die "$fv has uncommitted changes in tools/fn-modkit"
  local out=out-paktools
  "$fv/tools/win-build.sh" dotnet "$mirror" publish tools/fn-modkit/fn-modkit.csproj -c Release -o "$out" \
    -p:DebugType=none -p:DebugSymbols=false -p:Deterministic=true -p:ContinuousIntegrationBuild=true
  local tmp; tmp="$(mktemp -d "${TMPDIR:-/tmp}/rl-paktools.XXXXXX")"; trap 'rm -rf "$tmp"' EXIT
  ssh -o BatchMode=yes "${PC_HOST:-windows}" "tar -c -f - -C \"%LOCALAPPDATA%\\fp-build\\$mirror\\src\\$out\" ." | tar -x -f - -C "$tmp"
  import "$tmp" "$fv"
}

case "${1:-}" in
  update) shift; update "$@" ;;
  import) shift; import "$@" ;;
  check) check ;;
  header) header ;;
  *) sed -n '2,18p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
