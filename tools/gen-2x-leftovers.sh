#!/usr/bin/env bash
# gen-2x-leftovers.sh - write radarnite-2x-leftovers.nsh (the 2.x files the 3.x installer removes) from the listing of
# an installed 2.x (baseline/installed-2.2.1-files.tsv, made by baseline/measure-2x.ps1).
#   tools/gen-2x-leftovers.sh [listing.tsv] [out.nsh]
# Removed: every root file except user data and what 3.x installs again under the same name, and every top-level
# folder except the ones 3.x replaces as a whole (tools, gameserver, redirect, patches). config.json and *.log are
# never listed.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
IN="${1:-$ROOT/baseline/installed-2.2.1-files.tsv}"
OUT="${2:-$ROOT/radarnite-2x-leftovers.nsh}"
[ -f "$IN" ] || { echo "missing $IN" >&2; exit 1; }

keep_files='^(config\.json|radarnite\.ico|THIRD-PARTY-NOTICES\.txt|README-offline\.md|RadarniteLauncher\.exe|Uninstall Radarnite Launcher\.exe|.*\.log)$'
keep_dirs='^(tools|gameserver|redirect|patches)$'

files="$(tail -n +2 "$IN" | cut -f1 | tr -d '\r' | grep -v '\\' | grep -Ev "$keep_files" | LC_ALL=C sort -u)"
dirs="$( (tail -n +2 "$IN" | cut -f1 | tr -d '\r' | grep '\\' | cut -d'\' -f1; echo webview2-radarnite) | grep -Ev "$keep_dirs" | LC_ALL=C sort -u)"
if printf '%s\n%s\n' "$files" "$dirs" | grep -q '[$"`]'; then echo "a name needs NSIS escaping; refusing" >&2; exit 1; fi

{
  echo "; Generated by tools/gen-2x-leftovers.sh from $(basename "$IN"); do not edit by hand."
  echo "; What a 2.x program folder holds and 3.x no longer ships: the self-contained .NET runtime and its resource"
  echo "; folders, the WebView2 SDK, the page (ui), its browser profile (webview2-radarnite), Node and server.mjs."
  echo "; Removed tolerantly: a file in use stays and is reported, the install goes on. config.json and logs stay."
  echo "!macro Remove2xLeftovers"
  echo "  DetailPrint \"Removing files of Radarnite Launcher 2.x that 3.x no longer uses\""
  while IFS= read -r f; do [ -n "$f" ] && echo "  Delete \"\$INSTDIR\\$f\""; done <<<"$files"
  while IFS= read -r d; do [ -n "$d" ] && echo "  !insertmacro TolerantRMDir \"\$INSTDIR\\$d\""; done <<<"$dirs"
  echo "!macroend"
} > "$OUT"
echo "$OUT: $(grep -c '^  Delete' "$OUT") files, $(grep -c 'TolerantRMDir' "$OUT") folders"
